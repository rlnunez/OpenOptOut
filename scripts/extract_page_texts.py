#!/usr/bin/env python3
"""
Collect every phrase wrapped in tx("...") / txn(n, "...", "...") in the
frontend into backend/core/page_texts.json, the English list that language
packs translate (their texts.json).

    python scripts/extract_page_texts.py          # rewrite page_texts.json
    python scripts/extract_page_texts.py --check  # exit 1 if it's out of date

Strings must be plain literals ("..." or '...'), not variables, so they can
be found here. Placeholders look like {name}.

A few fixed help texts are sent by the server and shown with tx(value); they
are listed in SERVER_TEXTS and read from the Python source here.
"""
import ast
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "frontend", "src")
OUT = os.path.join(ROOT, "backend", "core", "page_texts.json")

_STR = r'''("(?:[^"\\\n]|\\.)*"|'(?:[^'\\\n]|\\.)*')'''
TX = re.compile(r"\btxr?\(\s*" + _STR)
TXN = re.compile(r"\btxn\(\s*[^,]+?,\s*" + _STR + r"\s*,\s*" + _STR)


def _decode(lit: str) -> str:
    if lit.startswith('"'):
        try:
            return json.loads(lit)
        except ValueError:
            pass
    return ast.literal_eval(lit)


def collect(src: str = SRC) -> dict:
    found = {}
    for dirpath, dirs, files in os.walk(src):
        dirs[:] = [d for d in dirs if d not in ("node_modules",)]
        for name in sorted(files):
            if not name.endswith((".js", ".jsx")):
                continue
            path = os.path.join(dirpath, name)
            rel = os.path.relpath(path, src).replace(os.sep, "/")
            if rel.startswith("i18n/"):
                continue
            text = open(path, encoding="utf-8").read()
            lits = [m.group(1) for m in TX.finditer(text)]
            for m in TXN.finditer(text):
                lits += [m.group(1), m.group(2)]
            for lit in lits:
                s = _decode(lit)
                if s.strip():
                    found.setdefault(s, set()).add(rel)
    return found


# Server-side constants that a screen shows through tx(value):
# (python file, variable name, key inside each dict value or None for a plain string)
SERVER_TEXTS = [
    ("backend/core/registry_sync.py", "SOURCES", "how"),
    ("backend/core/registry_sync.py", "REGISTRY_ENABLE_WARNING", None),
    ("backend/core/spec_drafter.py", "REHEARSAL_TEXTS", None),
    ("backend/core/spec_drafter.py", "WARNING_TEXTS", None),
    ("backend/core/ai_helpers.py", "PROVIDERS", "key_help"),
    ("backend/core/live_captcha.py", "STATES", None),
    ("backend/core/live_captcha.py", "PROBLEMS", None),
    ("backend/core/monitoring.py", "CHECK_TEXTS", None),
]


def collect_server(found: dict) -> dict:
    for rel, var, key in SERVER_TEXTS:
        tree = ast.parse(open(os.path.join(ROOT, rel), encoding="utf-8").read())
        for node in tree.body:
            if isinstance(node, ast.Assign) and any(getattr(t, "id", None) == var for t in node.targets):
                value = ast.literal_eval(node.value)
                if key:
                    items = [v[key] for v in value.values()]
                else:
                    items = list(value.values()) if isinstance(value, dict) else [value]
                for s in items:
                    if s.strip():
                        found.setdefault(s, set()).add("server: " + os.path.basename(rel))
    return found


def build(found: dict) -> dict:
    return {"_comment": "Generated by scripts/extract_page_texts.py. English is the key; "
                        "language packs translate these in texts.json.",
            "texts": [{"text": t, "where": sorted(found[t])} for t in sorted(found, key=lambda s: (s.lower(), s))]}


def main():
    data = build(collect_server(collect()))
    rendered = json.dumps(data, ensure_ascii=False, indent=1) + "\n"
    if "--check" in sys.argv:
        current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if current != rendered:
            print("page_texts.json is out of date: run python scripts/extract_page_texts.py")
            sys.exit(1)
        print(f"page_texts.json is up to date ({len(data['texts'])} phrases)")
        return
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(rendered)
    print(f"wrote {len(data['texts'])} phrases to {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
